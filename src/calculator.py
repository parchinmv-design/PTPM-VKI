"""
Класс вычислений / валидации.
Реализует расчёт скидки на товар (на основе Лабораторной работы №1).
"""


class DiscountCalculator:
    """Класс для расчёта скидок на товары."""

    def calculate_discount(self, price: float, quantity: int, is_vip: bool = False) -> float:
        """
        Рассчитывает итоговую стоимость покупки с учётом скидки.

        Правила скидок:
        - Базовая скидка 5% при покупке от 3 единиц товара.
        - Дополнительная скидка 10% при покупке от 10 единиц товара (суммируется с базовой).
        - VIP-клиенты получают дополнительную скидку 5% (суммируется с остальными).
        - Скидка не может превышать 25%.

        Args:
            price: Цена одной единицы товара (должна быть положительной).
            quantity: Количество единиц товара (должно быть положительным).
            is_vip: Признак VIP-клиента.

        Returns:
            Итоговая стоимость покупки.

        Raises:
            ValueError: Если цена или количество неположительные.
        """
        if price <= 0:
            raise ValueError("Цена должна быть положительной")
        if quantity <= 0:
            raise ValueError("Количество должно быть положительным")

        discount = 0.0

        if quantity >= 3:
            discount += 0.05
        if quantity >= 10:
            discount += 0.10
        if is_vip:
            discount += 0.05

        if discount > 0.25:
            discount = 0.25

        total = price * quantity * (1 - discount)
        return round(total, 2)
